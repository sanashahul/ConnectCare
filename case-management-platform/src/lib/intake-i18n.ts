export const INTAKE_LANGS = [
  { key: "en", label: "English", name: "English" },
  { key: "es", label: "Español", name: "Spanish" },
  { key: "vi", label: "Tiếng Việt", name: "Vietnamese" },
] as const;
export type IntakeLang = (typeof INTAKE_LANGS)[number]["key"];

export function intakeLang(value: string | null | undefined): IntakeLang {
  return INTAKE_LANGS.some((l) => l.key === value) ? (value as IntakeLang) : "en";
}

